"""Writes cli/src/logo.rs: rookery-circle.png as terminal art, one ink colour per character and a
2x3 sextant mask in it. Run it again only when the logo changes: python cli/logo.py
Stdlib only, so the PNG decoder handles what this file is: 8-bit RGBA, not interlaced."""
import json, pathlib, struct, zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
BODY, LEAF = (118, 160, 112), (168, 204, 104)   # heron, ring, nest / leaves
CUT = 0.42                                      # a sub-block is drawn at this much ink


def png(path):
    d = path.read_bytes()
    w, h, depth, kind, _, _, lace = struct.unpack(">IIBBBBB", d[16:29])
    assert (depth, kind, lace) == (8, 6, 0), "only 8-bit RGBA, not interlaced"
    i, idat = 8, b""
    while i < len(d):
        n, t = struct.unpack(">I4s", d[i:i + 8])
        if t == b"IDAT":
            idat += d[i + 8:i + 8 + n]
        i += 12 + n
    raw, st, rows, prev = zlib.decompress(idat), w * 4, [], bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (st + 1)], bytearray(raw[y * (st + 1) + 1:(y + 1) * (st + 1)])
        for x in range(st):
            a, b, c = (line[x - 4] if x >= 4 else 0), prev[x], (prev[x - 4] if x >= 4 else 0)
            if f == 1: line[x] = (line[x] + a) & 255
            elif f == 2: line[x] = (line[x] + b) & 255
            elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return w, h, rows


def grid(img, gw, gh):
    """-> gh rows of gw (ink 0..1, how much of that ink is leaf), area averaged"""
    w, h, px = img
    out = []
    for gy in range(gh):
        row = []
        for gx in range(gw):
            ink = leaf = n = 0
            for y in range(gy * h // gh, max(gy * h // gh + 1, (gy + 1) * h // gh)):
                for x in range(gx * w // gw, max(gx * w // gw + 1, (gx + 1) * w // gw)):
                    r, g, b, a = px[y][x * 4:x * 4 + 4]
                    lum = (r + g + b) / 3
                    k = a / 255 * max(0.0, min(1.0, (215 - lum) / 150))   # white and clear -> 0
                    ink += k
                    if k > 0.3 and g - b > 12 and lum > 55:
                        leaf += k
                    n += 1
            row.append((ink / n, leaf / ink if ink else 0))
        out.append(row)
    return out


def sextant(m):
    """bits: 1 top-left, 2 top-right, 4 middle-left, 8 middle-right, 16 bottom-left, 32 bottom-right"""
    special = {0: " ", 21: "▌", 42: "▐", 63: "█"}   # the four U+1FB00 leaves out
    return special.get(m) or chr(0x1FB00 + m - 1 - (m > 21) - (m > 42))


def art(img, cols):
    rows = cols // 2   # a character is twice as tall as it is wide, and the logo is round
    g = grid(img, cols * 2, rows * 3)
    lines = []
    for cy in range(rows):
        s, last = "", None
        for cx in range(cols):
            m = bit = 0
            ink = leaf = 0.0
            for dy in range(3):
                for dx in range(2):
                    i, l = g[cy * 3 + dy][cx * 2 + dx]
                    if i >= CUT:
                        m |= 1 << bit
                        ink += i
                        leaf += l * i
                    bit += 1
            t = leaf / ink if ink else 0
            c = tuple(round(BODY[k] + (LEAF[k] - BODY[k]) * t) for k in range(3))
            if m and c != last:
                s += "\x1b[38;2;%d;%d;%dm" % c
                last = c
            s += sextant(m)
        lines.append(s + "\x1b[0m")   # padded to `cols` on purpose: text goes beside it
    return lines


def rust(name, lines):
    body = "".join("    %s,\n" % json.dumps(l, ensure_ascii=False).replace("\\u001b", "\\x1b") for l in lines)
    return "pub const %s: &[&str] = &[\n%s];\n" % (name, body)


if __name__ == "__main__":
    img = png(ROOT / "rookery-circle.png")
    out = ROOT / "cli" / "src" / "logo.rs"
    out.write_bytes(("//! Generated by `python cli/logo.py` from rookery-circle.png: do not edit by hand.\n"
                     "//! Each line is the same number of characters wide, ending in a colour reset.\n\n"
                     + rust("LOGO", art(img, 28))).encode())
    print("wrote", out)
